// Builds seed/universities_us.json: US colleges students can pick in Student mode.
//
//   npm run schools:us                         community list (Hipo university-domains-list on GitHub)
//   npm run schools:us -- --scorecard KEY      official list from the US Dept. of Education's College Scorecard
//                                              (free key: https://api.data.gov/signup)
//
// Then run: npm run seed:build
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { hipoToUniversities, scorecardToUniversities, type HipoUniversity, type ScorecardSchool } from '../src/domain/usSchools';

const HIPO_URL = 'https://raw.githubusercontent.com/Hipo/university-domains-list/master/world_universities_and_domains.json';
const SCORECARD_URL = 'https://api.data.gov/ed/collegescorecard/v1/schools.json';

async function fromHipo(today: string) {
  const res = await fetch(HIPO_URL);
  if (!res.ok) throw new Error(`Download failed: ${res.status}`);
  return hipoToUniversities((await res.json()) as HipoUniversity[], HIPO_URL, today);
}

async function fromScorecard(key: string, today: string) {
  const schools: ScorecardSchool[] = [];
  for (let page = 0; ; page++) {
    const q = new URLSearchParams({
      api_key: key,
      'school.operating': '1',
      // Predominantly associate's, bachelor's or graduate degrees.
      'school.degrees_awarded.predominant': '2,3,4',
      fields: 'id,school.name,school.state,school.school_url',
      per_page: '100',
      page: String(page),
    });
    const res = await fetch(`${SCORECARD_URL}?${q}`);
    if (!res.ok) throw new Error(`College Scorecard request failed: ${res.status} ${await res.text()}`);
    const body = (await res.json()) as { results: ScorecardSchool[]; metadata: { total: number } };
    schools.push(...body.results);
    if (!body.results.length || schools.length >= body.metadata.total) break;
  }
  return scorecardToUniversities(schools, 'https://collegescorecard.ed.gov/data/', today);
}

async function main() {
  const today = new Date().toISOString().slice(0, 10);
  const i = process.argv.indexOf('--scorecard');
  const official = i >= 0;
  const universities = official ? await fromScorecard(process.argv[i + 1] ?? '', today) : await fromHipo(today);
  const file = {
    _readme: [
      'US colleges for Student mode. GENERATED by scripts/import-us-schools.ts — re-run it rather than editing.',
      official
        ? `Source: US Department of Education College Scorecard (operating, degree-granting), fetched ${today}.`
        : `Source: Hipo university-domains-list (community-maintained, not an official list), fetched ${today}. ` +
          'For the official list run: npm run schools:us -- --scorecard YOUR_API_DATA_GOV_KEY',
    ],
    universities,
  };
  const out = resolve(__dirname, '../seed/universities_us.json');
  writeFileSync(out, `${JSON.stringify(file, null, 2)}\n`);
  console.log(`Wrote ${universities.length} US schools to ${out}`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
