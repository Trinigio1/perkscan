// Validates the curated lists in seed/ and writes supabase/seed.sql.
// Usage: npm run seed:build
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { ZodType } from 'zod';
import {
  dealSourceFileSchema, dealSourcesToSql, eventFileSchema, eventsToSql, programFileSchema, programsToSql, settlementFileSchema, settlementsToSql, studentFileSchema, studentToSql, universitiesToSql, universityFileSchema, unknownUniversityIds,
} from '../src/domain/catalogSchema';
import { earnFileSchema, earnToSql } from '../src/domain/earnSchema';
import { seedFileSchema, seedToSql } from '../src/domain/seedSchema';

const root = resolve(__dirname, '..');
const output = resolve(root, 'supabase/seed.sql');

function load<T>(file: string, schema: ZodType<T>): T {
  const parsed = schema.safeParse(JSON.parse(readFileSync(resolve(root, file), 'utf8')));
  if (!parsed.success) {
    console.error(`${file} is invalid:`);
    for (const issue of parsed.error.issues) console.error(`  • ${issue.path.join('.')}: ${issue.message}`);
    process.exit(1);
  }
  return parsed.data;
}

const cardFile = load('seed/card_benefits.json', seedFileSchema);
// Memberships share the cards catalog (kind = 'membership'); they come after the cards.
const memberships = load('seed/memberships.json', seedFileSchema);
const cards = { ...cardFile, cards: [...cardFile.cards, ...memberships.cards.map((m) => ({ ...m, kind: 'membership' as const }))] };
const students = load('seed/student_discounts.json', studentFileSchema);
const settlements = load('seed/settlements.json', settlementFileSchema);
const programs = load('seed/programs.json', programFileSchema);
const events = load('seed/events.json', eventFileSchema);
const dealSources = load('seed/deal_sources.json', dealSourceFileSchema);
const earn = load('seed/earn_rates.json', earnFileSchema);
const ttSchools = load('seed/universities.json', universityFileSchema);
const usSchools = load('seed/universities_us.json', universityFileSchema);
const universities = { universities: [...ttSchools.universities, ...usSchools.universities] };
const dupes = universities.universities.map((u) => u.id).filter((id, i, all) => all.indexOf(id) !== i);
if (dupes.length) {
  console.error(`Duplicate school ids: ${[...new Set(dupes)].join(', ')}`);
  process.exit(1);
}
const unknown = unknownUniversityIds(students, universities);
if (unknown.length) {
  console.error(`seed/student_discounts.json points at schools that aren't in seed/universities.json: ${unknown.join(', ')}`);
  process.exit(1);
}

// seedToSql wraps the cards in begin/commit; the other lists go inside the same transaction.
const sql = seedToSql(cards).replace(/commit;\n$/, [
  '-- Schools (seed/universities.json)',
  ...universitiesToSql(universities),
  '-- Student offers (seed/student_discounts.json)',
  ...studentToSql(students),
  '-- Settlements (seed/settlements.json)',
  ...settlementsToSql(settlements),
  '-- Other places money hides (seed/programs.json)',
  ...programsToSql(programs),
  '-- Coming up near you (seed/events.json)',
  ...eventsToSql(events),
  '-- Pages the scout reads for deals and promotions (seed/deal_sources.json)',
  ...dealSourcesToSql(dealSources),
  '-- What each card earns where (seed/earn_rates.json)',
  ...earnToSql(earn, new Set(cards.cards.map((c) => c.id))),
  'commit;',
  '',
].join('\n'));
writeFileSync(output, sql);

// --migration: also write the same data (schools only with --with-schools) as a new migration, so a plain `supabase db push` loads it
// (the seed file only loads with --include-seed, which doesn't always run on hosted projects).
if (process.argv.includes('--migration')) {
  const dir = resolve(root, 'supabase/migrations');
  const latest = readdirSync(dir).filter((f) => /^\d{14}_.*\.sql$/.test(f)).sort().pop();
  // Numbered after the newest migration so it never lands "before" ones already pushed.
  const next = String(BigInt(latest ? latest.slice(0, 14) : '20260101000000') + 1n);
  const file = resolve(dir, `${next}_catalog_data.sql`);
  // Schools are big and rarely change: only include them with --with-schools.
  const withSchools = process.argv.includes('--with-schools');
  const schoolLines = new Set(universitiesToSql(universities));
  const body = sql
    .replace(/^-- GENERATED[^\n]*\n/, '')
    .replace(/^begin;\n/m, '')
    .replace(/commit;\n$/, '')
    .split('\n')
    .filter((line) => withSchools || !schoolLines.has(line))
    .join('\n');
  writeFileSync(
    file,
    `-- GENERATED by \`npm run seed:build -- --migration${withSchools ? ' --with-schools' : ''}\` from seed/*.json: cards, ${withSchools ? 'schools, ' : ''}student offers, settlements, programs, events.\n` +
      `-- Idempotent upserts, so it's safe alongside supabase/seed.sql.\n${body}`,
  );
  console.log(`Wrote ${file}`);
}

const benefits = cards.cards.flatMap((c) => c.benefits);
const todo = benefits.filter((b) => b.status === 'TODO_VERIFY').length;
const feesTodo = cards.cards.filter((c) => c.annual_fee === null).length;
console.log(`Wrote ${output}`);
console.log(`${cards.cards.length} cards, ${benefits.length} benefits — ${todo} benefits and ${feesTodo} annual fees still TODO_VERIFY.`);
console.log(`${universities.universities.length} schools, ${students.offers.length} student offers, ${settlements.settlements.length} settlements.`);
console.log(`${earn.cards.length} cards with earn rates (${earn.cards.reduce((n, c) => n + c.rates.length, 0)} rates).`);
console.log(`${events.events.length} events (${events.events.filter((e) => e.status === 'expected').length} expected).`);
console.log(`${programs.programs.length} programs — ${programs.programs.filter((p) => p.status === 'TODO_VERIFY').length} still TODO_VERIFY.`);
